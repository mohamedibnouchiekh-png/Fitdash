"use client";
import { useMemo } from "react";
import { AlertTriangle, CheckCircle2, Info, TrendingDown, TrendingUp, Minus } from "lucide-react";
import { useApp } from "@/lib/store";
import { computeInsights, trendSummary } from "@/lib/insights";
import { Card, EmptyState, Notice, PageHeader } from "@/components/ui";

export default function Insights() {
  const { ds, settings, today } = useApp();
  const { insights, withheld } = useMemo(() => computeInsights(ds, settings, today), [ds, settings, today]);
  const trends = useMemo(() => trendSummary(ds, settings, today), [ds, settings, today]);
  const icon = { attention: <AlertTriangle size={16} className="text-warn" aria-label="Needs attention" />, positive: <CheckCircle2 size={16} className="text-good" aria-label="Positive" />, info: <Info size={16} className="text-accent" aria-label="Information" /> };

  return (
    <>
      <PageHeader title="Insights" sub="Rule-based observations from your data. A rule only fires when it has enough data; otherwise it says why it stayed silent." />
      <Notice title="How to read these">Insights are generated by fixed, documented rules (no AI model, no guessing). They describe patterns and correlations in your own numbers; they do not prove causes and are not medical advice.</Notice>

      <div className="mt-4 grid gap-4 lg:grid-cols-[3fr_2fr]">
        <Card title={`What the data says (${insights.length})`}>
          {insights.length === 0 ? <EmptyState title="Nothing to report yet" body="More data is needed for the rules to say anything responsibly." /> : (
            <ul className="space-y-4">
              {insights.map((i) => (
                <li key={i.id} className="flex gap-3 border-b border-line pb-4 last:border-0 last:pb-0">
                  <span className="mt-0.5">{icon[i.severity]}</span>
                  <div><p className="text-sm font-semibold">{i.title}</p><p className="mt-0.5 text-sm text-mute">{i.body}</p><p className="mt-1 text-xs text-mute">Evidence: {i.evidence}</p></div>
                </li>
              ))}
            </ul>
          )}
        </Card>

        <div className="space-y-4">
          <Card title="What is changing?" info="Last 4 weeks compared with the 4 weeks before. “Stable” means a change smaller than the stated threshold for that metric.">
            <ul className="space-y-2">
              {trends.rows.map((r) => {
                const Icon = r.verdict === "improving" ? TrendingUp : r.verdict === "declining" ? TrendingDown : Minus;
                const good = r.neutral ? null : r.verdict === "improving" ? true : r.verdict === "declining" ? false : null;
                return (
                  <li key={r.id} className="text-sm"><div className="flex items-center justify-between gap-2"><span>{r.label}</span><span className={`inline-flex items-center gap-1 text-xs font-medium ${good === true ? "text-good" : good === false ? "text-bad" : "text-mute"}`}><Icon size={13} aria-hidden />{r.neutral && r.verdict !== "stable" ? (r.verdict === "improving" ? "up" : "down") : r.verdict}</span></div><p className="text-xs text-mute">{r.detail}</p></li>
                );
              })}
            </ul>
            {trends.skipped.length > 0 && <p className="mt-3 text-xs text-mute">Not enough data for: {trends.skipped.join(", ")}.</p>}
          </Card>

          <Card title={`Withheld for lack of data (${withheld.length})`} info="Each rule lists the minimum data it needs. Showing this keeps the dashboard honest about what it does not know.">
            {withheld.length === 0 ? <p className="text-sm text-mute">All rules had enough data.</p> : (
              <ul className="space-y-2.5 text-sm">{withheld.map((w) => (<li key={w.id}><p className="font-medium">{w.title}</p><p className="text-xs text-mute">{w.reason}</p></li>))}</ul>
            )}
          </Card>
        </div>
      </div>
    </>
  );
}
